"""Generate the printable BikeSense ArUco scale cards (A4 PDF) and a PNG for tests.

The marker gives Python a millimetre scale in photos and videos (chain sag, drip-patch area)
and a pose to check that before/after shots were framed the same way.

Outputs (in docs/):
  aruco_card.pdf   A4 page, two cut-out cards: A = chain/swingarm (ID 0), B = drip cardboard / dipstick (ID 1)
  aruco_card.png   one marker with a white margin (used by scripts/smoke_test.py for the SAM test)
  aruco_card.json  dictionary, IDs and nominal size; put your *measured* printed size in it after printing

Print at 100% / "Actual size" (no "Fit to page"), then measure the black square with a ruler.
Self-check: the script renders the page, re-detects both markers and checks the scale.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import cv2
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib.patches import Rectangle  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
DICT_NAME = "DICT_4X4_50"
MARKER_MM = 50.0  # side of the black square
A4_W, A4_H = 210.0, 297.0
MM_PER_INCH = 25.4
CARDS = [
    {"id": 0, "label": "Card A: CHAIN", "where": "Tape to the swingarm, level with the chain, facing the camera.", "top": 38.0},
    {"id": 1, "label": "Card B: OIL", "where": "Place on the drip cardboard / next to the dipstick, flat, facing the camera.", "top": 160.0},
]


def marker_bits(marker_id: int) -> np.ndarray:
    """6x6 cell matrix (True = black) incl. the 1-cell black border."""
    d = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, DICT_NAME))
    img = cv2.aruco.generateImageMarker(d, marker_id, 6, borderBits=1)
    return img < 128


def draw_marker(ax, bits: np.ndarray, x0: float, y0: float, side: float) -> None:
    cell = side / bits.shape[0]
    for r in range(bits.shape[0]):
        for c in range(bits.shape[1]):
            if bits[r, c]:
                ax.add_patch(Rectangle((x0 + c * cell, y0 + r * cell), cell, cell, color="black", lw=0))


def draw_scale_bar(ax, x0: float, y: float, length: float = 100.0) -> None:
    ax.plot([x0, x0 + length], [y, y], color="black", lw=1.2)
    for mm in range(0, int(length) + 1):
        h = 4.0 if mm % 10 == 0 else (2.5 if mm % 5 == 0 else 1.2)
        ax.plot([x0 + mm, x0 + mm], [y, y - h], color="black", lw=0.5 if mm % 10 else 0.9)
        if mm % 10 == 0:
            ax.text(x0 + mm, y + 3.5, str(mm), ha="center", va="center", fontsize=6)
    ax.text(x0 + length + 3, y, "mm: this bar must measure exactly 100 mm", va="center", fontsize=7)


def make_pdf(path: Path) -> plt.Figure:
    fig = plt.figure(figsize=(A4_W / MM_PER_INCH, A4_H / MM_PER_INCH))
    ax = fig.add_axes((0, 0, 1, 1))
    ax.set_xlim(0, A4_W)
    ax.set_ylim(A4_H, 0)  # y grows downward, in mm
    ax.axis("off")

    ax.text(15, 14, "BikeSense scale cards", fontsize=16, weight="bold", va="center")
    ax.text(15, 22, 'Print at 100% / "Actual size" (NOT "Fit to page"). Then measure the black square side with a ruler',
            fontsize=8, va="center")
    ax.text(15, 27, "and write it in docs/aruco_card.json as measured_marker_mm. Keep the cards flat; don't cover the white margin.",
            fontsize=8, va="center")

    for card in CARDS:
        top = card["top"]
        ax.add_patch(Rectangle((12, top), 186, 112, fill=False, ls=(0, (4, 3)), lw=0.6, color="0.4"))
        ax.text(14, top + 3.5, "cut", fontsize=6, color="0.4", va="center")
        mx, my = 25.0, top + 12.0
        # white quiet zone is the paper itself; keep >= 1 cell (8.3 mm) around the marker
        draw_marker(ax, marker_bits(card["id"]), mx, my, MARKER_MM)
        tx = mx + MARKER_MM + 14
        ax.text(tx, my + 4, card["label"], fontsize=13, weight="bold", va="center")
        ax.text(tx, my + 12, f"ArUco {DICT_NAME}, ID {card['id']}", fontsize=8, va="center")
        ax.text(tx, my + 18, f"Black square side (nominal): {MARKER_MM:.0f} mm", fontsize=8, va="center")
        ax.text(tx, my + 26, card["where"], fontsize=7, va="center", wrap=True)
        ax.text(tx, my + 36, "Measured side: ______ mm", fontsize=9, va="center")
        ax.text(tx, my + 44, "Same card, same spot for before AND after scans.", fontsize=7, va="center", style="italic")
        draw_scale_bar(ax, 25.0, top + 82.0)

    ax.text(15, 286, "Generated by scripts/make_aruco_card.py (BikeSense, Meta AI Developer Hackathon 2026).",
            fontsize=6, color="0.4", va="center")
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, format="pdf")
    return fig


def make_png(path: Path, marker_id: int = 0, px: int = 600) -> None:
    d = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, DICT_NAME))
    img = cv2.aruco.generateImageMarker(d, marker_id, px, borderBits=1)
    img = cv2.copyMakeBorder(img, px // 6, px // 6, px // 6, px // 6, cv2.BORDER_CONSTANT, value=255)
    cv2.imwrite(str(path), img)


def self_check(fig: plt.Figure, dpi: int = 200) -> bool:
    """Render the page, detect both markers, and check their side length in mm."""
    fig.canvas.draw()
    fig.set_dpi(dpi)
    fig.canvas.draw()
    rgba = np.asarray(fig.canvas.buffer_rgba())
    gray = cv2.cvtColor(rgba, cv2.COLOR_RGBA2GRAY)
    det = cv2.aruco.ArucoDetector(cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, DICT_NAME)),
                                  cv2.aruco.DetectorParameters())
    corners, ids, _ = det.detectMarkers(gray)
    found = sorted(int(i) for i in ids.flatten()) if ids is not None else []
    print(f"self-check: detected IDs {found} (expected {[c['id'] for c in CARDS]})")
    ok = found == sorted(c["id"] for c in CARDS)
    px_per_mm = dpi / MM_PER_INCH
    for c in corners:
        pts = c.reshape(4, 2)
        side_px = np.mean([np.linalg.norm(pts[i] - pts[(i + 1) % 4]) for i in range(4)])
        side_mm = side_px / px_per_mm
        print(f"self-check: marker side = {side_mm:.2f} mm (nominal {MARKER_MM:.0f} mm)")
        ok &= abs(side_mm - MARKER_MM) < 1.0
    return ok


def main() -> int:
    pdf, png, meta = DOCS / "aruco_card.pdf", DOCS / "aruco_card.png", DOCS / "aruco_card.json"
    fig = make_pdf(pdf)
    make_png(png)
    meta_existed = meta.exists()
    if not meta_existed:  # never overwrite a measured value
        meta.write_text(json.dumps({
            "dictionary": DICT_NAME,
            "cards": {"chain": 0, "oil": 1},
            "nominal_marker_mm": MARKER_MM,
            "measured_marker_mm": None,
            "note": "After printing, measure the black square side with a ruler and set measured_marker_mm.",
        }, indent=2) + "\n", encoding="utf-8")
    ok = self_check(fig)
    print(f"wrote {pdf}\nwrote {png}\n{'kept existing' if meta_existed else 'wrote'} {meta}")
    print("SELF-CHECK PASSED" if ok else "SELF-CHECK FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
